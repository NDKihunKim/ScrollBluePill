import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const supabaseUrl = process.env.SUPABASE_URL;
const supabaseAnonKey = process.env.SUPABASE_ANON_KEY;
const outputPath = resolve('public/data/scrolls.json');
const overridesPath = resolve('data/scroll-visibility-overrides.json');
const reportPath = resolve('docs/data-quality/scroll-visibility-report.md');

if (!supabaseUrl || !supabaseAnonKey) {
	console.error('SUPABASE_URL and SUPABASE_ANON_KEY environment variables are required.');
	console.error('Copy .env.example to .env and fill in your Supabase project credentials.');
	process.exit(1);
}

const supabaseRestUrl = new URL('/rest/v1/scroll_definitions', supabaseUrl);
supabaseRestUrl.searchParams.set('select', '*');

async function fetchSupabase(url, options = {}) {
	const response = await fetch(url, {
		...options,
		headers: {
			apikey: supabaseAnonKey,
			authorization: `Bearer ${supabaseAnonKey}`,
			...(options.headers ?? {}),
		},
	});

	if (!response.ok) {
		const body = await response.text().catch(() => '');
		throw new Error(`Supabase API error ${response.status}: ${body}`);
	}

	return response.json();
}

const DESIRED_PERCENTS = new Set([10, 60, 100]);
const PERCENT_PATTERN = /(\d+)%$/;

function filterDesiredPercentScrolls(scrolls) {
	return scrolls.filter((scroll) => {
		const match = scroll.name_ko?.match(PERCENT_PATTERN);
		if (!match) {
			return false;
		}

		const percent = Number(match[1]);
		return DESIRED_PERCENTS.has(percent);
	});
}

function applyVisibilityOverrides(scrolls, overrides) {
	const hiddenIds = new Set(overrides.hideScrollIds ?? []);
	const hiddenCategories = new Set(overrides.hideCategories ?? []);
	const hiddenBehaviorTypes = new Set(overrides.hideBehaviorTypes ?? []);
	const renameById = overrides.renameById ?? {};

	const visible = scrolls
		.filter((scroll) => !hiddenIds.has(scroll.id))
		.filter((scroll) => !hiddenCategories.has(scroll.category))
		.filter((scroll) => !hiddenBehaviorTypes.has(scroll.behavior_type))
		.map((scroll) => {
			const rename = renameById[scroll.id];
			if (!rename) {
				return scroll;
			}

			return {
				...scroll,
				name_ko: rename.nameKo ?? scroll.name_ko,
			};
		});

	return {
		scrolls: visible,
		hiddenIds,
		hiddenCategories,
		hiddenBehaviorTypes,
		renamedIds: new Set(Object.keys(renameById)),
	};
}

async function writeReport(scrolls, visibilitySummary) {
	const { hiddenIds, hiddenCategories, hiddenBehaviorTypes, renamedIds } = visibilitySummary;

	const categoryCounts = new Map();
	for (const scroll of scrolls) {
		const category = scroll.category ?? '(none)';
		categoryCounts.set(category, (categoryCounts.get(category) ?? 0) + 1);
	}

	const behaviorTypeCounts = new Map();
	for (const scroll of scrolls) {
		const bt = scroll.behavior_type ?? '(none)';
		behaviorTypeCounts.set(bt, (behaviorTypeCounts.get(bt) ?? 0) + 1);
	}

	const allAffectedStats = new Set();
	for (const scroll of scrolls) {
		for (const stat of scroll.affected_stats ?? []) {
			allAffectedStats.add(stat);
		}
	}

	const lines = [
		'# Scroll Visibility Report',
		'',
		'Generated by `scripts/generate-scroll-index.mjs`.',
		'',
		`Total visible scrolls: ${scrolls.length}`,
		'',
		'## Visibility Overrides',
		'',
		`- Hidden scroll IDs: ${[...hiddenIds].join(', ') || '-'}`,
		`- Hidden categories: ${[...hiddenCategories].join(', ') || '-'}`,
		`- Hidden behavior types: ${[...hiddenBehaviorTypes].join(', ') || '-'}`,
		`- Renamed scroll IDs: ${[...renamedIds].join(', ') || '-'}`,
		'',
		'## Visible Scrolls by Category',
		'',
		'| Category | Count |',
		'| --- | ---: |',
		...[...categoryCounts].sort(([a], [b]) => String(a).localeCompare(String(b), 'ko')).map(([cat, count]) => `| ${cat} | ${count} |`),
		'',
		'## Visible Scrolls by Behavior Type',
		'',
		'| Behavior Type | Count |',
		'| --- | ---: |',
		...[...behaviorTypeCounts].sort(([a], [b]) => String(a).localeCompare(String(b), 'ko')).map(([bt, count]) => `| ${bt} | ${count} |`),
		'',
		'## Affected Stats Across Visible Scrolls',
		'',
		[...allAffectedStats].sort().map((stat) => `- ${stat}`).join('\n'),
		'',
	];

	await mkdir(dirname(reportPath), { recursive: true });
	await writeFile(reportPath, `${lines.join('\n')}\n`);
}

async function main() {
	const overrides = JSON.parse(await readFile(overridesPath, 'utf8'));

	console.log('Fetching scroll definitions from Supabase...');
	const rawScrolls = await fetchSupabase(supabaseRestUrl);
	console.log(`Fetched ${rawScrolls.length} scroll definitions (RLS-filtered to published only).`);

	const visibilityResult = applyVisibilityOverrides(rawScrolls, overrides);
	let { scrolls } = visibilityResult;

	const beforePercentFilter = scrolls.length;
	scrolls = filterDesiredPercentScrolls(scrolls);
	console.log(`Percent filter: kept ${scrolls.length} scrolls (10%, 60%, 100% only; removed ${beforePercentFilter - scrolls.length}).`);

	const sorted = [...scrolls].sort((a, b) => a.name_ko.localeCompare(b.name_ko, 'ko-KR'));

	await mkdir(dirname(outputPath), { recursive: true });
	await writeFile(outputPath, `${JSON.stringify(sorted, null, 2)}\n`);
	await writeReport(sorted, visibilityResult);

	console.log(`Generated ${outputPath} with ${sorted.length}/${rawScrolls.length} scrolls.`);
	console.log(
		`Visibility overrides: ${visibilityResult.hiddenIds.size} hidden by ID; ` +
		`${visibilityResult.hiddenCategories.size} categories hidden; ` +
		`${visibilityResult.hiddenBehaviorTypes.size} behavior types hidden; ` +
		`${visibilityResult.renamedIds.size} renamed.`,
	);
	console.log(`Scroll visibility report: ${reportPath}`);
}

await main();
