import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { CHAOS_SCROLLS } from './chaos-scroll-defs.mjs';

const supabaseUrl = process.env.SUPABASE_URL;
const supabaseAnonKey = process.env.SUPABASE_ANON_KEY;
const outputPath = resolve('public/data/scrolls-gms83-ko.json');
const overridesPath = resolve('data/scroll-visibility-overrides.json');
const reportPath = resolve('docs/data-quality/scroll-visibility-report.md');

if (!supabaseUrl || !supabaseAnonKey) {
	console.log('Skipping scroll index sync — SUPABASE_URL/ANON_KEY not set (using committed data).');
	process.exit(0);
}

const PERCENT_PATTERN = /(\d+)%$/;

async function fetchSupabase(url, options = {}) {
	const response = await fetch(url, {
		...options,
		headers: {
			apikey: supabaseAnonKey,
			authorization: `Bearer ${supabaseAnonKey}`,
			...(options.headers ?? {}),
		},
	});

	if (!response.ok) {
		const body = await response.text().catch(() => '');
		throw new Error(`Supabase API error ${response.status}: ${body}`);
	}

	return response.json();
}

function transformToFrontendSchema(row) {
	return {
		id: row.maplestory_io_item_id,
		nameKo: row.name_ko,
		equipmentKind: row.category,
		behavior_type: row.behavior_type,
		stats: row.stat_effect_frame ?? {},
		targetItemId: row.target_item_id ?? null,
		maxApplications: row.max_applications ?? null,
	};
}

function applyVisibilityOverrides(scrolls, overrides) {
	const hiddenIds = new Set(overrides.hideScrollIds ?? []);
	const hiddenCategories = new Set(overrides.hideCategories ?? []);
	const hiddenBehaviorTypes = new Set(overrides.hideBehaviorTypes ?? []);
	const renameById = overrides.renameById ?? {};

	const visible = scrolls
		.filter((scroll) => !hiddenIds.has(scroll.maplestory_io_item_id))
		.filter((scroll) => !hiddenCategories.has(scroll.category))
		.filter((scroll) => !hiddenBehaviorTypes.has(scroll.behavior_type))
		.map((scroll) => {
			const rename = renameById[scroll.maplestory_io_item_id];
			if (!rename) {
				return scroll;
			}

			return {
				...scroll,
				name_ko: rename.nameKo ?? scroll.name_ko,
			};
		});

	return {
		scrolls: visible,
		hiddenIds,
		hiddenCategories,
		hiddenBehaviorTypes,
		renamedIds: new Set(Object.keys(renameById)),
	};
}

async function writeReport(frontendScrolls, visibilitySummary) {
	const { hiddenIds, hiddenCategories, hiddenBehaviorTypes, renamedIds } = visibilitySummary;

	const categoryCounts = new Map();
	for (const scroll of frontendScrolls) {
		const kind = scroll.equipmentKind ?? '(none)';
		categoryCounts.set(kind, (categoryCounts.get(kind) ?? 0) + 1);
	}

	const behaviorTypeCounts = new Map();
	for (const scroll of frontendScrolls) {
		const bt = scroll.behavior_type ?? '(none)';
		behaviorTypeCounts.set(bt, (behaviorTypeCounts.get(bt) ?? 0) + 1);
	}

	const allAffectedStats = new Set();
	for (const scroll of frontendScrolls) {
		for (const stat of Object.keys(scroll.stats ?? {})) {
			allAffectedStats.add(stat);
		}
	}

	const lines = [
		'# Scroll Visibility Report',
		'',
		'Generated by `scripts/generate-scroll-index.mjs`.',
		'',
		`Total visible scrolls: ${frontendScrolls.length}`,
		'',
		'## Visibility Overrides',
		'',
		`- Hidden scroll IDs: ${[...hiddenIds].join(', ') || '-'}`,
		`- Hidden categories: ${[...hiddenCategories].join(', ') || '-'}`,
		`- Hidden behavior types: ${[...hiddenBehaviorTypes].join(', ') || '-'}`,
		`- Renamed scroll IDs: ${[...renamedIds].join(', ') || '-'}`,
		'',
		'## Visible Scrolls by Category',
		'',
		'| Category | Count |',
		'| --- | ---: |',
		...[...categoryCounts].sort(([a], [b]) => String(a).localeCompare(String(b), 'ko')).map(([cat, count]) => `| ${cat} | ${count} |`),
		'',
		'## Visible Scrolls by Behavior Type',
		'',
		'| Behavior Type | Count |',
		'| --- | ---: |',
		...[...behaviorTypeCounts].sort(([a], [b]) => String(a).localeCompare(String(b), 'ko')).map(([bt, count]) => `| ${bt} | ${count} |`),
		'',
		'## Affected Stats Across Visible Scrolls',
		'',
		[...allAffectedStats].sort().map((stat) => `- ${stat}`).join('\n'),
		'',
	];

	await mkdir(dirname(reportPath), { recursive: true });
	await writeFile(reportPath, `${lines.join('\n')}\n`);
}

async function main() {
	const overrides = JSON.parse(await readFile(overridesPath, 'utf8'));

	console.log('Fetching scroll definitions from Supabase...');
	const supabaseRestUrl = new URL('/rest/v1/scroll_definitions', supabaseUrl);
	supabaseRestUrl.searchParams.set('select', '*');
	const rawScrolls = await fetchSupabase(supabaseRestUrl);
	console.log(`Fetched ${rawScrolls.length} scroll definitions (RLS-filtered to published only).`);

	// Apply visibility overrides on raw Supabase rows
	const visibilityResult = applyVisibilityOverrides(rawScrolls, overrides);
	const { scrolls: visibleScrolls } = visibilityResult;

	// Transform to frontend camelCase schema, drop rows with null item IDs.
	// Visibility is governed by published_status in the database (published = visible).
	const frontendScrolls = visibleScrolls
		.filter((row) => row.maplestory_io_item_id != null)
		.map(transformToFrontendSchema);

	const droppedNullIds = visibleScrolls.length - frontendScrolls.length;
	if (droppedNullIds > 0) {
		console.log(`Dropped ${droppedNullIds} scrolls with null maplestory_io_item_id.`);
	}

	// ── Inject chaos scrolls ──────────────────────────────────────────────
	// Chaos scrolls do not exist in Supabase (they are not regular scrolls
	// with fixed stat contributions).  They are injected here so that the
	// deconstruction calculator's chaos strategy enumeration has entries
	// with behavior_type === 'chaos' to match against.  Each chaos scroll
	// has all stats at 0 because chaos provides random deltas via an
	// outcome table, not fixed values.
	//
	// When Supabase eventually includes chaos scroll rows, deduplicate by
	// ID to avoid doubling-up.

	const _existingIds = new Set(frontendScrolls.map((s) => s.id));
	let _chaosInjected = 0;
	for (const chaos of CHAOS_SCROLLS) {
		if (!_existingIds.has(chaos.id)) {
			frontendScrolls.push({ ...chaos });
			_chaosInjected++;
		}
	}
	if (_chaosInjected > 0) {
		console.log(`Injected ${_chaosInjected} chaos scroll entries (${CHAOS_SCROLLS.length - _chaosInjected} already present in DB).`);
	}

	// Stat priority by stats object keys: weaponAttack > magicAttack > str > dex > int > luk > rest
	const STAT_KEY_RANK = {
		weaponAttack: 0,
		magicAttack: 1,
		str: 2,
		dex: 3,
		int: 4,
		luk: 5,
	};

	const getStatPriority = (stats) => {
		const keys = Object.keys(stats ?? {});
		let best = 99;
		for (const key of keys) {
			const rank = STAT_KEY_RANK[key];
			if (rank !== undefined && rank < best) best = rank;
		}
		return best;
	};

	const stemName = (name) => String(name ?? '').replace(PERCENT_PATTERN, '').trimEnd();

	// Sort: equipmentKind → stat priority → name stem → percent descending (100→60→10)
	//
	// Normalize stat priority within name-stem groups so same-named scrolls
	// (e.g. 점프력 100% and 점프력 60%) stay together even when their secondary
	// stats differ (60% version has dex which pulls it into a higher tier).
	const extractPercent = (name) => {
		const match = name?.match(PERCENT_PATTERN);
		return match ? Number(match[1]) : 0;
	};

	const stemBestPriority = new Map();
	for (const scroll of frontendScrolls) {
		const stem = stemName(scroll.nameKo);
		const priority = getStatPriority(scroll.stats);
		const current = stemBestPriority.get(stem);
		if (current === undefined || priority < current) {
			stemBestPriority.set(stem, priority);
		}
	}

	const sortPriority = (scroll) => stemBestPriority.get(stemName(scroll.nameKo)) ?? 99;

	frontendScrolls.sort((a, b) =>
		String(a.equipmentKind).localeCompare(String(b.equipmentKind), 'ko-KR') ||
		sortPriority(a) - sortPriority(b) ||
		stemName(a.nameKo).localeCompare(stemName(b.nameKo), 'ko-KR') ||
		extractPercent(b.nameKo) - extractPercent(a.nameKo),
	);

	await mkdir(dirname(outputPath), { recursive: true });
	await writeFile(outputPath, `${JSON.stringify(frontendScrolls, null, 2)}\n`);
	await writeReport(frontendScrolls, visibilityResult);

	console.log(`Generated ${outputPath} with ${frontendScrolls.length}/${rawScrolls.length} scrolls.`);
	console.log(
		`Visibility overrides: ${visibilityResult.hiddenIds.size} hidden by ID; ` +
		`${visibilityResult.hiddenCategories.size} categories hidden; ` +
		`${visibilityResult.hiddenBehaviorTypes.size} behavior types hidden; ` +
		`${visibilityResult.renamedIds.size} renamed.`,
	);
	console.log(`Scroll visibility report: ${reportPath}`);
}

await main();
